def calc_rel_spatial_coverage_of_subset(doc: dict, geo) -> float:
    urls = sorted(doc['metadata']['product_urls'])
    urls = [url for url in urls if '.tif' == url[-4:]]
    url = urls[0]
    try:
        X, _ = crop_raster_from_bounds(url, geo.bounds)
        val = (X != 255).sum() / X.size
    except ValueError:
        val = 0
    return val


